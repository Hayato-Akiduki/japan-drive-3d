    static MapData()
    {
        Build();
        // 分岐の番号が直感的になるよう、北から時計回りに並べる
        foreach (var c in Cities)
            c.Roads.Sort((x, y) => Bearing(c, x.NextPointFrom(c)).CompareTo(Bearing(c, y.NextPointFrom(c))));
    }

    public static City Get(string name) => ByName[name];

    private static double Bearing(City from, (double Lat, double Lon) to)
    {
        double dx = (to.Lon - from.Lon) * Math.Cos(from.Lat * Math.PI / 180);
        double dy = to.Lat - from.Lat;
        double deg = Math.Atan2(dx, dy) * 180 / Math.PI;
        return deg < 0 ? deg + 360 : deg;
    }

    private static void C(string name, double lat, double lon, bool goal = false)
    {
        var c = new City(name, lat, lon, goal);
        Cities.Add(c);
        ByName[name] = c;
    }

    private static void R(string road, string a, string b, double km, RoadType type = RoadType.Expressway, params (double Lat, double Lon)[] waypoints)
    {
        var r = new Road(road, Get(a), Get(b), km, type, waypoints);
        Roads.Add(r);
        r.A.Roads.Add(r);
        r.B.Roads.Add(r);
    }

    private static void R(string road, string a, string b, double km, params (double Lat, double Lon)[] waypoints) =>
        R(road, a, b, km, RoadType.Expressway, waypoints);

