namespace JapanDrive;

public enum RoadType { Expressway, Bridge, Ferry, MegaBridge }

public sealed class City
{
    public City(string name, double lat, double lon, bool isGoal)
    {
        Name = name;
        Lat = lat;
        Lon = lon;
        IsGoal = isGoal;
    }

    public string Name { get; }
    public double Lat { get; }
    public double Lon { get; }
    /// <summary>★目的地（日本一周で必ず訪れる都市）</summary>
    public bool IsGoal { get; }
    public List<Road> Roads { get; } = new();

    public override string ToString() => Name;
}

public sealed class Road
{
    public Road(string name, City a, City b, double km, RoadType type, params (double Lat, double Lon)[] waypoints)
    {
        Name = name;
        A = a;
        B = b;
        Km = km;
        Type = type;
        var pts = new (double Lat, double Lon)[waypoints.Length + 2];
        pts[0] = (a.Lat, a.Lon);
        for (int i = 0; i < waypoints.Length; i++)
            pts[i + 1] = waypoints[i];
        pts[pts.Length - 1] = (b.Lat, b.Lon);
        Points = pts;
    }

    public string Name { get; }
    public City A { get; }
    public City B { get; }
    public double Km { get; }
    public RoadType Type { get; }
    /// <summary>A → 中間ウェイポイント → B の折れ線座標列</summary>
    public (double Lat, double Lon)[] Points { get; }

    public City Other(City c) => c == A ? B : A;

    public (double Lat, double Lon) NextPointFrom(City c) =>
        c == A ? Points[1] : Points[Points.Length - 2];

    /// <summary>進行率 t (0..1) における折れ線上の緯度・経度</summary>
    public (double Lat, double Lon) Sample(double t)
    {
        t = Math.Clamp(t, 0.0, 1.0);
        if (Points.Length <= 2)
        {
            return (
                A.Lat + (B.Lat - A.Lat) * t,
                A.Lon + (B.Lon - A.Lon) * t);
        }
        int segs = Points.Length - 1;
        Span<double> lens = stackalloc double[segs];
        double total = 0;
        for (int i = 0; i < segs; i++)
        {
            double dy = Points[i + 1].Lat - Points[i].Lat;
            double dx = (Points[i + 1].Lon - Points[i].Lon) * Math.Cos((Points[i].Lat + Points[i + 1].Lat) * 0.5 * Math.PI / 180.0);
            double l = Math.Sqrt(dx * dx + dy * dy);
            lens[i] = l;
            total += l;
        }
        if (total <= 1e-9) return Points[0];
        double target = total * t;
        double acc = 0;
        for (int i = 0; i < segs; i++)
        {
            if (acc + lens[i] >= target || i == segs - 1)
            {
                double u = lens[i] > 1e-9 ? (target - acc) / lens[i] : 0;
                return (
                    Points[i].Lat + (Points[i + 1].Lat - Points[i].Lat) * u,
                    Points[i].Lon + (Points[i + 1].Lon - Points[i].Lon) * u);
            }
            acc += lens[i];
        }
        return Points[^1];
    }

    /// <summary>通行料金（簡易計算）</summary>
    public int Toll => Type switch
    {
        RoadType.Ferry => 18000,
        RoadType.Bridge => RoundTen(Km * 60 + 150),
        RoadType.MegaBridge => RoundTen(Km * 20 + 500),
        _ => RoundTen(Km * 25 + 150),
    };

    private static int RoundTen(double v) => (int)(Math.Round(v / 10) * 10);
}

